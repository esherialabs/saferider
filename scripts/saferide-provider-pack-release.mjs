#!/usr/bin/env node

import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { canonicalSha256 } from './lib/saferide-provider-pack.mjs';
import { runProviderPackCheck } from './saferide-provider-pack-check.mjs';

function valueAfter(flag) {
  const index = process.argv.indexOf(flag);
  return index === -1 ? undefined : process.argv[index + 1];
}

export function runProviderPackRelease(options = {}) {
  const result = runProviderPackCheck({ ...options, release: true });
  return {
    ...result,
    packSha256: canonicalSha256(result.pack),
    manifestSha256: canonicalSha256(result.manifest),
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = runProviderPackRelease({
    packPath: valueAfter('--pack'),
    manifestPath: valueAfter('--manifest'),
    controlsPath: valueAfter('--controls'),
    partnerPath: valueAfter('--partner-validation'),
    attestationPath: valueAfter('--attestation'),
  });
  if (result.errors.length) {
    console.error(`Provider pack release remains blocked (${result.errors.length}):`);
    for (const error of result.errors) console.error(`- ${error}`);
    console.error('Supply hash-bound partner validation and release attestation files, then rerun against the exact candidate. No approval is generated by this tool.');
    process.exitCode = 1;
  } else {
    console.log(`Provider pack release gate passed for ${result.pack.packId}@${result.pack.version}.`);
    console.log(`Pack SHA-256: ${result.packSha256}`);
    console.log(`Manifest SHA-256: ${result.manifestSha256}`);
  }
}
